// QUA-23 : les listes des contraintes CHECK (migration 0017) sont celles de l'interface ; une valeur ajoutée d'un côté
// seulement échoue ici (et demande une nouvelle migration).

const same = (a: readonly string[], b: readonly string[]) => expect([...a].sort()).toEqual([...b].sort());

describe('clés des colonnes d’état (QUA-23)', () => {
  it('identiques aux listes de l’interface', () => {
    same(EVENT_TYPE_CODES, EVENT_TYPE_KEYS);
    same(EVENT_STEP_KINDS, ['advance', 'revert', 'reopen', 'dismiss', 'restore'] satisfies EventTransition[]);
    same(REVIEW_STATUS_CODES, Object.keys(REVIEW_STATUS));
    same(REVIEW_KIND_CODES, REVIEW_KIND_KEYS);
    same(REVIEW_DECISION_KIND_CODES, REVIEW_DECISION_KEYS);
    same(PLAN_STATUS_CODES, Object.keys(PLAN_STATUS));
    // État stocké d'un permis : l'état affiché ajoute « en cours » et « expiré », calculés (permitState).
    same(PERMIT_STATUS_CODES, Object.keys(PERMIT_STATE).filter((k) => k !== 'en_cours' && k !== 'expire'));
    same(PERMIT_TYPE_CODES, PERMIT_TYPE_KEYS);
    same(EVALUATION_CODES, Object.keys(REQUIREMENT_EVAL));
    same(FINDING_KIND_CODES, Object.keys(FINDING_KINDS));
    same(BSD_STATUS_CODES, BSD_STATUS_KEYS);
    same(REQUIREMENT_LINK_CODES, REQUIREMENT_LINK_KEYS);
    // Paquet 13 (migration 0020).
    same(CONTROL_CATEGORY_CODES, CONTROL_CATEGORY_KEYS);
    same(SAFETY_NOTICE_KIND_CODES, SAFETY_NOTICE_KIND_KEYS);
    same(PLAN_MEETING_KIND_CODES, PLAN_MEETING_KIND_KEYS);
    same(MEASURE_LINK_KIND_CODES, MEASURE_LINK_KIND_KEYS);
    // Paquet 13, seconde moitié (migration 0021).
    same(CHANGE_KIND_CODES, CHANGE_KIND_KEYS);
    same(CHANGE_STATUS_CODES, CHANGE_STATUS_KEYS);
    // Études de sécurité des procédés (VG-01, migration 0023).
    same(STUDY_MILESTONE_CODES, STUDY_MILESTONE_KEYS);
    same(STUDY_TYPE_CODES, STUDY_TYPE_KEYS);
    same(STUDY_STATUS_CODES, STORED_STUDY_STATUS_KEYS);
    same(STUDY_CONCLUSION_CODES, STUDY_CONCLUSION_KEYS);
    // Convergence M-02 (migration 0024) : état d'un site dans Matrix, passages des connecteurs, origine d'une affectation.
    same(MATRIX_STATE_CODES, Object.keys(MATRIX_SITE_STATES));
    same(CURSUS_TITLE_STATE_CODES, Object.keys(CURSUS_TITLE_STATES));
    // D01, décision CV-10 (migration 0030) : personnes lues dans Cursus.
    same(CURSUS_PERSON_STATE_CODES, Object.keys(CURSUS_PERSON_STATES));
    same(PERSON_CATEGORY_CODES, Object.keys(PERSON_CATEGORIES));
    same(SYNC_STATUS_CODES, Object.keys(SYNC_STATUSES));
    same(ASSIGNMENT_SOURCE_CODES, Object.keys(ASSIGNMENT_SOURCES));
    // D13, décision CV-08 (migration 0026) : demandes reçues de Keystone.
    same(INBOUND_STATUS_CODES, Object.keys(INBOUND_STATUSES));
    same([...INBOUND_KIND_CODES, ...ENGINEERING_INBOUND_KIND_CODES], Object.keys(INBOUND_KINDS));
    // D12, lot 5 de M-02 (migration 0029) : modifications techniques et envois aux outils.
    same(ECO_TYPE_CODES, ECO_TYPE_KEYS);
    same(ECO_STATUS_CODES, ECO_STATUS_KEYS);
    same(ECR_KIND_CODES, ECR_KIND_KEYS);
    same(ECR_SUBJECT_CODES, ECR_SUBJECT_KEYS);
    same(ECR_STATUS_CODES, ECR_STATUS_KEYS);
    same(ENGINEERING_SOURCE_CODES, Object.keys(ENGINEERING_SOURCES));
    same(ECO_APPROVAL_KEY_CODES, ECO_APPROVAL_KEY_LIST);
    same(ECO_DECISION_CODES, Object.keys(ECO_DECISIONS));
    same(ECO_APPROVAL_VIA_CODES, ['vigie', 'keystone']);
    same(EFFECTIVITY_TARGET_CODES, Object.keys(EFFECTIVITY_TARGETS));
    same(EFFECTIVITY_DISPOSITION_CODES, EFFECTIVITY_DISPOSITION_KEYS);
    same(OUTBOUND_STATUS_CODES, Object.keys(OUTBOUND_STATUSES));
    same(OUTBOUND_TARGET_CODES, Object.keys(OUTBOUND_TARGETS));
    same(OUTBOUND_KIND_CODES, Object.keys(OUTBOUND_KINDS));
    same(INBOUND_RESULT_CODES, Object.keys(INBOUND_RESULTS));
  });
});
