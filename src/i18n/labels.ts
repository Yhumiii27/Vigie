/** Dictionnaire français des chaînes sources de LABEL_EN : LABEL_EN inversé (le français est le libellé de la table). */
export const LABELS_FR: Record<string, string> = Object.fromEntries(Object.entries(LABEL_EN).map(([fr, en]) => [en, fr]));
/** Chaînes sources identiques en français (« Actions », « DUERP », « 20 % »…). */
export const LABELS_SAME: readonly string[] = Object.entries(LABEL_EN).filter(([fr, en]) => fr === en).map(([, en]) => en);

/** Traducteur des libellés de tables : chaîne source anglaise rendue par t(), libellé inconnu rendu tel quel. */
export const labelT = (t: T) => (label: string): string => {
  const en = Object.hasOwn(LABEL_EN, label) ? LABEL_EN[label] : undefined;
  return en ? t(en) : label;
};
